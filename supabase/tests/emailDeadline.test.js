test('deadline expires only unanswered released main invitations and records why', async () => {
  const result=await setDeadline(past());
  assert.equal(result.expired_count,1);
  const rows=await q('SELECT id,status,released_status,invitation_response,invitation_expired_at FROM registrations ORDER BY id');
  assert.equal(rows[0].released_status,'rejected'); assert.equal(rows[0].invitation_response,'declined'); assert.ok(rows[0].invitation_expired_at);
  assert.equal(rows[1].invitation_response,'accepted'); assert.equal(rows[1].released_status,'approved');
  assert.equal(rows[2].invitation_response,'declined'); assert.equal(rows[2].released_status,'approved');
  assert.equal(rows[3].status,'pending'); assert.equal(rows[4].released_status,'approved');
  assert.equal(await expire(),0,'repeat expiry has no extra effects');
});
test('late responses fail at the database boundary even before the scheduled expiry pass', async () => {
  await setDeadline(future());
  await db.exec("UPDATE invitation_settings SET deadline=clock_timestamp()-interval '1 millisecond'");
  await assert.rejects(respond(1),/deadline has passed/);
  assert.equal((await respond(2)).invitation_response,'accepted','an accepted retry remains idempotent');
  assert.equal(await expire(),1);
  await assert.rejects(respond(1,'declined'),/deadline has passed/);
});
test('a response received before the deadline survives expiry; unreleased and other-form applications stay protected', async () => {
  await setDeadline(future());
  await respond(1);
  await db.exec("UPDATE invitation_settings SET deadline=clock_timestamp()-interval '1 second'");
  assert.equal(await expire(),0);
  assert.equal((await respond(1)).invitation_response,'accepted');
  await assert.rejects(respond(4),/No released invitation/);
  await assert.rejects(respond(5),/No registration/);
});
test('deadline updates reject stale versions; clearing or extending cannot revive expired invitations', async () => {
  await setDeadline(future());
  await assert.rejects(setDeadline(past(),1),/deadline changed/);
  await db.exec("UPDATE invitation_settings SET deadline=clock_timestamp()-interval '1 second'");
  assert.equal((await setDeadline(future(),2)).expired_count,1);
  assert.equal(await one('SELECT invitation_response FROM registrations WHERE id=1'),'declined');
  await setDeadline(null,3); assert.equal(await one('SELECT invitation_response FROM registrations WHERE id=1'),'declined');
  await db.exec("UPDATE registrations SET status='approved' WHERE id=1");
  await setDeadline(future(),4); await release(1);
  assert.equal(await one('SELECT invitation_response FROM registrations WHERE id=1'),null);
  assert.equal(await one('SELECT invitation_expired_at FROM registrations WHERE id=1'),null);
});
test('approval release and email queue reject closed or missing deadlines; changing deadline invalidates previews and queued emails', async () => {
  await assert.rejects(queue(await draft()),/deadline changed or has passed/);
  await setDeadline(future());
  const stale=await draft();
  const queued=await draft(); await queue(queued);
  assert.equal(await one('SELECT template_version FROM email_outbox'),'saved-v3');
  await setDeadline(new Date(Date.now()+172800000).toISOString(),2);
  assert.equal(await one('SELECT state FROM email_outbox'),'cancelled');
  await assert.rejects(queue(stale),/deadline changed or has passed/);
  await queue(await draft()); assert.equal(await one("SELECT count(*)::int FROM email_outbox WHERE state='queued'"),1);
  await db.exec("UPDATE invitation_settings SET deadline=clock_timestamp()-interval '1 second'");
  assert.deepEqual(await q('SELECT * FROM claim_email_job()'),[]);
  await assert.rejects(release(6),/deadline has passed/);
});
