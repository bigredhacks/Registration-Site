async function draft(n = 1) {
  const r = (await q('SELECT * FROM registrations WHERE id=$1',[n]))[0];
  const version = await one("SELECT version FROM invitation_settings WHERE id='registration'");
  return one('INSERT INTO email_batches(kind,created_by,messages,invitation_settings_version) VALUES ($1,$2,$3,$4) RETURNING id', ['approved', uid(9), JSON.stringify([{ id:r.id,recipient:r.email,released_at:r.decision_released_at,payload:{to:r.email,html:'<p>Reviewed</p>'},template_version:'saved-v3' }]), version]);
}
const queue = id => one('SELECT queue_decision_email_batch($1,$2)',[id,uid(9)]);

