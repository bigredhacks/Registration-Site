test('a reviewed corrected recipient replaces a never-attempted cancelled email exactly once', async () => {
  await setDeadline(future()); await queue(await draft());
  const originalId=await one('SELECT id FROM email_outbox');
  await db.exec("UPDATE registrations SET email='corrected@example.com' WHERE id=1");
  assert.deepEqual(await q('SELECT * FROM claim_email_job()'),[]);
  assert.equal(await one('SELECT state FROM email_outbox'),'cancelled');
  const replacement=await draft();
  const otherPreview=await draft();
  assert.deepEqual(await queue(replacement),{queued:1,skipped:0});
  assert.deepEqual(await queue(otherPreview),{queued:0,skipped:1});
  assert.deepEqual(await queue(replacement),{queued:1,skipped:0},'repeating the same request returns its original result');
  const [job]=await q('SELECT * FROM claim_email_job()');
  assert.equal(job.id,originalId);
  assert.equal(job.batch_id,replacement);
  assert.equal(job.recipient,'corrected@example.com');
  assert.equal(job.request_payload.to,'corrected@example.com');
  assert.equal(job.attempts,1);
});
test('replacement previews cannot overwrite queued, attempted, uncertain or sent messages', async () => {
  await setDeadline(future()); await queue(await draft());
  const original=await one('SELECT request_payload FROM email_outbox');
  await db.exec("UPDATE registrations SET email='corrected@example.com' WHERE id=1");
  for (const state of ['queued','sending','failed','needs_review','sent','cancelled']) {
    await db.query('UPDATE email_outbox SET state=$1,first_attempt_at=now(),attempts=1',[state]);
    assert.deepEqual(await queue(await draft()),{queued:0,skipped:1},state);
    assert.deepEqual(await one('SELECT request_payload FROM email_outbox'),original);
  }
});
