const test = require('node:test');
const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const path = require('node:path');
const { PGlite } = require('@electric-sql/pglite');
let db;
const uid = n => `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
const query = async (sql, params = []) => (await db.query(sql, params)).rows;
const scalar = async (sql, params) => Object.values((await query(sql, params))[0])[0];
const migration = name => readFileSync(path.join(__dirname, '../migrations', name), 'utf8');
const registration = n => ({ user_id: uid(n), form_key: 'registration', form_version: 1, first_name: 'Alex', last_name: 'Test', email: `alex${n}@example.com`, answers: { first_name: 'Alex', custom: ['nested', true] } });
const create = n => scalar('SELECT to_jsonb(public.create_registration_with_email($1::jsonb))', [JSON.stringify(registration(n))]);
const release = (id, status = 'approved') => scalar("SELECT count(*) FROM public.release_registration_decisions($1::jsonb)", [JSON.stringify([{ id, expected_status: status }])]);
async function batch(ids, kind = 'approved') {
  const rows = await query('SELECT * FROM registrations WHERE id = ANY($1::bigint[]) ORDER BY id', [ids]);
  const messages = rows.map(r => ({ id: r.id, recipient: r.email, released_at: r.decision_released_at,
    payload: { from: 'test@example.com', to: r.email, subject: kind, html: '<p>Test</p>', text: 'Test' } }));
  return scalar('INSERT INTO email_batches(kind,created_by,messages) VALUES ($1,$2,$3) RETURNING id', [kind, uid(9), JSON.stringify(messages)]);
}
const queue = id => scalar('SELECT public.queue_decision_email_batch($1,$2)', [id, uid(9)]);
const claim = () => query('SELECT * FROM public.claim_email_job()');

