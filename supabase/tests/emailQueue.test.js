test('submission and confirmation are atomic; duplicates create neither extra applications nor jobs', async () => {
  const r = await create(1);
  assert.equal(r.status, 'pending'); assert.deepEqual(r.answers, registration(1).answers);
  assert.deepEqual(await query('SELECT recipient,first_name,form_title,state FROM email_outbox'), [{ recipient: 'alex1@example.com', first_name: 'Alex', form_title: 'BigRed//Hacks', state: 'queued' }]);
  await assert.rejects(create(1), /duplicate key/);
  assert.equal(await scalar('SELECT count(*)::int FROM email_outbox'), 1);
  await db.exec('RESET ROLE; REVOKE INSERT ON email_outbox FROM service_role; SET ROLE service_role;');
  await assert.rejects(create(2), /permission denied/);
  assert.equal(await scalar('SELECT count(*)::int FROM registrations'), 1, 'queue failure rolls back application');
  await db.exec('RESET ROLE; GRANT INSERT ON email_outbox TO service_role; SET ROLE service_role;');
});

test('database rechecks form version, closure, and activity at submission', async () => {
  for (const [sql, pattern] of [["UPDATE form_configs SET version=2", /form changed/], ["UPDATE form_configs SET version=1,closes_at=now()-interval '1 minute'", /Registration is closed/], ['UPDATE form_configs SET closes_at=null,is_active=false', /Active form not found/]]) {
    await db.exec(sql); await assert.rejects(create(1), pattern);
  }
  assert.equal(await scalar('SELECT count(*)::int FROM registrations'), 0);
  assert.equal(await scalar('SELECT count(*)::int FROM email_outbox'), 0);
});

test('decision queue requires released decisions, snapshots the preview, and deduplicates across batches', async () => {
  const r = await create(1);
  await db.exec("UPDATE registrations SET status='approved'; DELETE FROM email_outbox;");
  await assert.rejects(queue(await batch([r.id])), /changed/);
  await release(r.id);
  const id = await batch([r.id]);
  assert.deepEqual(await queue(id), { queued: 1, skipped: 0 });
  assert.deepEqual(await queue(id), { queued: 1, skipped: 0 });
  assert.deepEqual(await queue(await batch([r.id])), { queued: 0, skipped: 1 });
  assert.equal(await scalar('SELECT count(*)::int FROM email_outbox'), 1);
  assert.equal((await scalar('SELECT request_payload FROM email_outbox')).to, r.email);
});

test('changed recipient or released decision invalidates an entire preview without partial queueing', async () => {
  const a = await create(1), b = await create(2);
  await db.exec("UPDATE registrations SET status='approved'; DELETE FROM email_outbox;");
  await release(a.id); await release(b.id);
  const id = await batch([a.id, b.id]);
  await db.exec("UPDATE registrations SET email='changed@example.com' WHERE id=2");
  await assert.rejects(queue(id), /changed/);
  assert.equal(await scalar('SELECT count(*)::int FROM email_outbox'), 0);
  assert.equal(await scalar('SELECT queued_at FROM email_batches WHERE id=$1', [id]), null);
  await db.exec("UPDATE registrations SET email='alex2@example.com',status='rejected' WHERE id=2");
  await release(b.id, 'rejected');
  await assert.rejects(queue(id), /changed/);
});

test('claim leases one job, recovers expired leases with the same identity, and stops at 23 hours', async () => {
  await create(1);
  const first = (await claim())[0];
  assert.equal(first.attempts, 1); assert.equal(first.state, 'sending');
  assert.deepEqual(await claim(), []);
  await db.exec("UPDATE email_outbox SET lease_until=now()-interval '1 second'");
  const retry = (await claim())[0];
  assert.equal(retry.id, first.id); assert.notEqual(retry.lease_token, first.lease_token); assert.equal(retry.attempts, 2);
  await db.exec("UPDATE email_outbox SET lease_until=now()-interval '1 second',first_attempt_at=now()-interval '23 hours 1 minute'");
  assert.deepEqual(await claim(), []);
  assert.equal(await scalar('SELECT state FROM email_outbox'), 'needs_review');
  assert.equal(await scalar('SELECT retry_email_job($1)', [first.id]), false);
});

test('worker cancels stale decisions or deleted registrations; safe failures may be retried', async () => {
  const r = await create(1);
  await db.exec("UPDATE registrations SET status='approved'; DELETE FROM email_outbox;");
  await release(r.id); await queue(await batch([r.id]));
  await db.exec("UPDATE registrations SET status='rejected'"); await release(r.id, 'rejected');
  assert.deepEqual(await claim(), []);
  assert.equal(await scalar('SELECT state FROM email_outbox'), 'cancelled');
  const rejected = await batch([r.id], 'rejected'); await queue(rejected);
  const job = (await claim())[0]; assert.equal(job.kind, 'rejected');
  await db.exec("UPDATE email_outbox SET state='failed',lease_token=null,lease_until=null WHERE kind='rejected'");
  assert.equal(await scalar('SELECT retry_email_job($1)', [job.id]), true);
  await db.exec('DELETE FROM registrations');
  assert.deepEqual(await claim(), []);
  assert.equal(await scalar('SELECT state FROM email_outbox WHERE id=$1', [job.id]), 'cancelled');
});

